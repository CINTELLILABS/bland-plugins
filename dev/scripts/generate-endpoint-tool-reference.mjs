import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const server = process.argv[2];
assert.ok(server, 'Usage: node dev/scripts/generate-endpoint-tool-reference.mjs <SERVER checkout> [--check]');
const dir = resolve(server, 'apps/api/src/lib/blandcode/actions/endpoints/generated');
const rows = [];
for (const file of readdirSync(dir).filter((name) => name.endsWith('.ts')).sort()) {
  const source = readFileSync(resolve(dir, file), 'utf8');
  for (const match of source.matchAll(/\n\t\{\n\t\tname: "([^"]+)",([\s\S]*?)(?=\n\t\},)/g)) {
    const [, name, block] = match;
    const field = (key) => new RegExp(`\\n\\t\\t${key}:\\s*"([^"]+)"`).exec(block)?.[1];
    const keys = (key) => {
      const value = new RegExp(`\\n\\t\\t${key}: \\[([\\s\\S]*?)\\]`).exec(block)?.[1];
      return value ? [...value.matchAll(/"([^"]+)"/g)].map((m) => m[1]) : [];
    };
    const method = field('method');
    const path = field('path');
    const docsPage = field('docsPage');
    assert.ok(method && path && docsPage, `Incomplete spec: ${name}`);
    rows.push({ name, method, path, docsPage, pathParams: keys('pathParams'),
      queryParams: keys('queryParams'), bodyParams: keys('bodyParams') });
  }
}
assert.ok(rows.length > 250, `Expected full endpoint set, found ${rows.length}`);
assert.equal(new Set(rows.map((row) => row.name)).size, rows.length, 'Duplicate tool names');
rows.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`, 'en'));
const text = '# Named endpoint tool index\n\n'
  + '<!-- Generated by dev/scripts/generate-endpoint-tool-reference.mjs; do not edit by hand. -->\n'
  + 'Source: [SERVER PR #12407](https://github.com/CINTELLILABS/SERVER/pull/12407).\n\n'
  + 'Use this index only to find an exact method + route fallback when a generic\n'
  + 'proxy is absent. It is not proof a tool is connected or permitted. Inspect the\n'
  + 'live schema for required fields and types; send named fields at the top level,\n'
  + 'not a generic `path`, `query`, or `body` envelope. Existing curated tools such\n'
  + 'as `get_agent`, `save_agent_version`, `get_call_log`, `validate_pathway`,\n'
  + '`upload_knowledge_file`, and `save_code_snippet` are not generated here; inspect\n'
  + 'their live contracts separately. No tool in this index covers legacy pathway\n'
  + 'workspace saves or pathway chat simulation.\n\n'
  + rows.map((row) => {
    const params = ['pathParams', 'queryParams', 'bodyParams'].flatMap((key) =>
      row[key].length ? [`${key.replace('Params', '')} fields: ${row[key].map((name) => `\`${name}\``).join(', ')}`] : []);
    return `- \`${row.method} ${row.path}\` → \`${row.name}\` ([docs](https://docs.bland.ai/${row.docsPage}))`
      + (params.length ? `; ${params.join('; ')}` : '; no input fields') + '.';
  }).join('\n') + '\n';
for (const target of ['skills/api/references/endpoint-tools.md', 'v2/skills/api-workspace/references/endpoint-tools.md']) {
  if (process.argv.includes('--check')) assert.equal(readFileSync(resolve(root, target), 'utf8'), text, target);
  else writeFileSync(resolve(root, target), text);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${rows.length} endpoint mappings in both plugins`);
